package com.uai.buslines.adapter.out.persistence;

import com.uai.buslines.domain.model.GtfsRoute;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Unit test — verifies that {@link LineMapper} round-trips a
 * {@link GtfsRoute} through the entity representation without data loss.
 */
class LineMapperTest {

    @Test
    void toEntity_setsAllFieldsCorrectly() {
        GtfsRoute route = new GtfsRoute("R001", "9400", "Bairro A - Centro");

        LineEntity entity = LineMapper.toEntity(route, 7L);

        assertThat(entity.getGtfsRouteId()).isEqualTo("R001");
        assertThat(entity.getShortName()).isEqualTo("9400");
        assertThat(entity.getLongName()).isEqualTo("Bairro A - Centro");
        assertThat(entity.getDatasetVersion()).isEqualTo(7L);
        assertThat(entity.getId()).isNull(); // generated by DB
    }

    @Test
    void toDomain_reconstructsOriginalRoute() {
        GtfsRoute original = new GtfsRoute("R002", "2010", "Centro - Bairro B");

        LineEntity entity = LineMapper.toEntity(original, 3L);
        GtfsRoute restored = LineMapper.toDomain(entity);

        assertThat(restored).isEqualTo(original);
    }

    @Test
    void roundTrip_preservesRouteIdAsBusinessKey() {
        // route_id is the join key for line_shape and line_neighborhood
        GtfsRoute route = new GtfsRoute("ROUTE-XYZ-999", "short", "long name here");

        LineEntity entity = LineMapper.toEntity(route, 1L);
        GtfsRoute restored = LineMapper.toDomain(entity);

        assertThat(restored.routeId()).isEqualTo("ROUTE-XYZ-999");
    }

    @Test
    void toEntity_differentVersionIds_produceDifferentVersionTags() {
        GtfsRoute route = new GtfsRoute("R001", "9400", "Bairro A - Centro");

        LineEntity v1 = LineMapper.toEntity(route, 1L);
        LineEntity v2 = LineMapper.toEntity(route, 2L);

        assertThat(v1.getDatasetVersion()).isEqualTo(1L);
        assertThat(v2.getDatasetVersion()).isEqualTo(2L);
        assertThat(v1.getGtfsRouteId()).isEqualTo(v2.getGtfsRouteId());
    }
}
