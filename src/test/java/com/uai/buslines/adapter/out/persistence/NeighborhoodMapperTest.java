package com.uai.buslines.adapter.out.persistence;

import com.uai.buslines.BoundaryFixtures;
import com.uai.buslines.domain.model.Neighborhood;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Unit test — verifies that {@link NeighborhoodMapper} round-trips a
 * {@link Neighborhood} through the entity representation without data loss.
 */
class NeighborhoodMapperTest {

    @Test
    void toEntity_setsAllFieldsCorrectly() {
        Neighborhood n = new Neighborhood(BoundaryFixtures.CENTRO_NAME, BoundaryFixtures.CENTRO_GEOJSON);

        NeighborhoodEntity entity = NeighborhoodMapper.toEntity(n, 42L);

        assertThat(entity.getName()).isEqualTo(BoundaryFixtures.CENTRO_NAME);
        assertThat(entity.getBoundaryGeoJson()).isEqualTo(BoundaryFixtures.CENTRO_GEOJSON);
        assertThat(entity.getDatasetVersion()).isEqualTo(42L);
        assertThat(entity.getId()).isNull(); // generated by DB — not set yet
    }

    @Test
    void toDomain_reconstructsOriginalNeighborhood() {
        Neighborhood original = new Neighborhood(BoundaryFixtures.BAIRRO_A_NAME,
                BoundaryFixtures.BAIRRO_A_GEOJSON);

        NeighborhoodEntity entity = NeighborhoodMapper.toEntity(original, 7L);
        Neighborhood restored = NeighborhoodMapper.toDomain(entity);

        assertThat(restored).isEqualTo(original);
    }

    @Test
    void roundTrip_preservesAllThreeFixtureNeighborhoods() {
        for (Neighborhood n : BoundaryFixtures.threeNeighborhoods()) {
            NeighborhoodEntity entity = NeighborhoodMapper.toEntity(n, 1L);
            Neighborhood restored = NeighborhoodMapper.toDomain(entity);
            assertThat(restored).as("round-trip for '%s'", n.name()).isEqualTo(n);
        }
    }

    @Test
    void boundaryGeoJson_isPassedThroughUnchanged() {
        // GeoJSON string must reach the DB verbatim — no re-serialization
        String geoJson = BoundaryFixtures.BAIRRO_B_GEOJSON;
        Neighborhood n = new Neighborhood("Bairro B", geoJson);

        NeighborhoodEntity entity = NeighborhoodMapper.toEntity(n, 99L);

        assertThat(entity.getBoundaryGeoJson()).isSameAs(geoJson);
    }
}
